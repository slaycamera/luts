#!/usr/bin/env node
/**
 * Generates the original slay starter LUT pack as .cube files.
 *
 * Every look is a pure colour transform, sampled on a 33×33×33 grid.
 * Output lands in luts/ and can be reproduced byte-for-byte by running:
 *
 *   node tools/generate-luts.mjs
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "luts");
const SIZE = 33;

// ---------------------------------------------------------------- helpers

const clamp01 = (x) => (x < 0 ? 0 : x > 1 ? 1 : x);
const mix = (a, b, t) => a + (b - a) * t;
const luma = ([r, g, b]) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

/** Smoothstep contrast around mid-grey. `amount` 0 = none, 1 = full S-curve. */
const contrast = (x, amount) => mix(x, x * x * (3 - 2 * x), amount);

const contrastRGB = (rgb, amount) => rgb.map((x) => contrast(x, amount));

/** Pushes colours away from (or towards) mid-grey luma. */
const saturate = (rgb, amount) => {
  const y = luma(rgb);
  return rgb.map((x) => mix(y, x, amount));
};

/** Linear lift/gain: remaps [0, 1] to [lift, gain]. */
const toneCurve = (rgb, lift, gain) => rgb.map((x) => lift + x * (gain - lift));

/** Adds a tint to shadows and highlights, scaled by luma. */
const splitTone = (rgb, shadows, highlights) => {
  const y = luma(rgb);
  return rgb.map((x, i) => x + shadows[i] * (1 - y) + highlights[i] * y);
};

const multiply = (rgb, gains) => rgb.map((x, i) => x * gains[i]);

// ------------------------------------------------------------------ looks

const looks = [
  {
    file: "slay-01-amber.cube",
    title: "slay Amber",
    note: "Golden-hour glow — warm highlights, gentle contrast.",
    transform: (v) => {
      let rgb = multiply(v, [1.05, 1.01, 0.97]); // warm white balance
      rgb = contrastRGB(rgb, 0.35);
      rgb = saturate(rgb, 1.08);
      rgb = splitTone(rgb, [0.0, 0.0, -0.012], [0.05, 0.015, -0.03]);
      return rgb;
    },
  },
  {
    file: "slay-02-fade.cube",
    title: "slay Fade",
    note: "Matte film fade — lifted blacks, muted colour.",
    transform: (v) => {
      let rgb = toneCurve(v, 0.09, 0.92);
      rgb = contrastRGB(rgb, 0.08);
      rgb = saturate(rgb, 0.82);
      rgb = splitTone(rgb, [0.02, 0.0, 0.01], [0.0, -0.005, 0.02]);
      return rgb;
    },
  },
  {
    file: "slay-03-neon.cube",
    title: "slay Neon",
    note: "Night-city punch — cyan shadows, magenta highlights, extra colour.",
    transform: (v) => {
      let rgb = v.map((x) => x * 1.04 - 0.015); // slight black crush
      rgb = contrastRGB(rgb, 0.5);
      rgb = saturate(rgb, 1.25);
      rgb = splitTone(rgb, [-0.045, 0.02, 0.06], [0.07, -0.03, 0.05]);
      return rgb;
    },
  },
  {
    file: "slay-04-film.cube",
    title: "slay Film",
    note: "Classic filmic — deep contrast, teal shadows, warm skin.",
    transform: (v) => {
      let rgb = toneCurve(v, 0.015, 0.985);
      rgb = contrastRGB(rgb, 0.4);
      rgb = saturate(rgb, 1.02);
      rgb = splitTone(rgb, [-0.02, 0.005, 0.045], [0.045, 0.01, -0.025]);
      return rgb;
    },
  },
  {
    file: "slay-05-portrait.cube",
    title: "slay Portrait",
    note: "Soft and flattering — warm skin, gentle roll-off.",
    transform: (v) => {
      let rgb = multiply(v, [1.035, 1.0, 0.97]);
      rgb = toneCurve(rgb, 0.035, 0.955);
      rgb = contrastRGB(rgb, 0.14);
      rgb = saturate(rgb, 1.0);
      rgb = splitTone(rgb, [0.012, -0.006, 0.006], [0.02, 0.005, -0.015]);
      return rgb;
    },
  },
];

// ----------------------------------------------------------------- render

function buildCube({ title, transform }, size) {
  const rows = [];
  // .cube ordering: red changes fastest, blue slowest.
  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const out = transform([r / (size - 1), g / (size - 1), b / (size - 1)]);
        rows.push(out.map((x) => clamp01(x).toFixed(6)).join(" "));
      }
    }
  }

  const header = [
    `TITLE "${title}"`,
    `# Generated by slay — https://www.slaycamera.com`,
    `# License: CC BY 4.0 — free to use with attribution (slaycamera.com)`,
    `LUT_3D_SIZE ${size}`,
    `DOMAIN_MIN 0.0 0.0 0.0`,
    `DOMAIN_MAX 1.0 1.0 1.0`,
    ``,
  ].join("\n");

  return header + rows.join("\n") + "\n";
}

await mkdir(OUT_DIR, { recursive: true });

for (const look of looks) {
  const path = join(OUT_DIR, look.file);
  await writeFile(path, buildCube(look, SIZE), "utf8");
  console.log(`wrote ${path}`);
}
